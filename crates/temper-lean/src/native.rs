//! Native Lean calls from Rust.

use crate::{identity, manifest::Metric, toolchain::VerifiedCandidate};
use anyhow::{Context, Result, ensure};
use std::sync::Mutex;

type Call = unsafe extern "C" fn(*const u8, usize, *mut usize) -> *mut u8;
type Free = unsafe extern "C" fn(*mut u8);

// Lean module initializers are not thread-safe, including when two reviewed
// handles load the same library. This is an FFI lifecycle lock, not app state.
static INITIALIZATION: Mutex<()> = Mutex::new(());

/// Review attached to one exact native artifact and tenant.
pub struct ReviewedCandidate {
    candidate: VerifiedCandidate,
    reviewer: String,
}

impl ReviewedCandidate {
    /// Record an explicit deployment review. The caller must authenticate the
    /// reviewer; a descendant requires its own artifact-bound review.
    pub fn approve(
        candidate: VerifiedCandidate,
        tenant: &str,
        expected_id: &str,
        reviewer: &str,
    ) -> Result<Self> {
        ensure!(
            candidate.spec.manifest.tenant == tenant,
            "review tenant mismatch"
        );
        ensure!(candidate.id == expected_id, "review artifact mismatch");
        ensure!(
            !reviewer.trim().is_empty(),
            "deployment reviewer is required"
        );
        Ok(Self {
            candidate,
            reviewer: reviewer.into(),
        })
    }

    /// Load only the reviewed artifact into the host service.
    pub fn load(self) -> Result<NativeCore> {
        NativeCore::load(self.candidate, Some(self.reviewer))
    }
}

/// Native Lean core callable from a Rust service after deployment review.
///
/// The service owns authentication, authorization, state, persistence, and effects.
/// Core calls are serialized; no ambient I/O is part of the String -> String ABI.
pub struct NativeCore {
    // Keep the library loaded until after all function pointers are dropped.
    _library: libloading::Library,
    candidate: VerifiedCandidate,
    call: Call,
    free: Free,
    lock: Mutex<()>,
    reviewer: Option<String>,
}

impl NativeCore {
    fn load(candidate: VerifiedCandidate, reviewer: Option<String>) -> Result<Self> {
        let _initialization = INITIALIZATION
            .lock()
            .map_err(|_| anyhow::anyhow!("Lean initialization lock poisoned"))?;
        ensure!(
            identity(&[&std::fs::read(&candidate.library)?]) == candidate.artifact_hash,
            "native artifact changed after proof checking"
        );
        // SAFETY: the library and bridge are generated by Toolchain from checked
        // source. Their exact bytes were just matched to the verification result.
        let library = unsafe { libloading::Library::new(&candidate.library)? };
        let (initialize, call, free) = unsafe {
            (
                *library.get::<unsafe extern "C" fn() -> i32>(b"temper_initialize\0")?,
                *library.get::<Call>(b"temper_call\0")?,
                *library.get::<Free>(b"temper_free\0")?,
            )
        };
        ensure!(unsafe { initialize() } == 0, "Lean initialization failed");
        Ok(Self {
            _library: library,
            candidate,
            call,
            free,
            lock: Mutex::new(()),
            reviewer,
        })
    }

    /// Invoke using the explicit owning tenant. Rust service authorization must
    /// already have succeeded. Input and output are UTF-8 and may contain NULs.
    pub fn invoke(&self, tenant: &str, input: &str) -> Result<String> {
        ensure!(
            tenant == self.candidate.spec.manifest.tenant,
            "Lean tenant mismatch"
        );
        let _guard = self
            .lock
            .lock()
            .map_err(|_| anyhow::anyhow!("Lean call lock poisoned"))?;
        let mut size = 0usize;
        let ptr = unsafe { (self.call)(input.as_ptr(), input.len(), &mut size) };
        ensure!(!ptr.is_null(), "Lean response allocation failed");
        let bytes = unsafe { std::slice::from_raw_parts(ptr, size).to_vec() };
        unsafe { (self.free)(ptr) };
        String::from_utf8(bytes).context("Lean response is not UTF-8")
    }

    /// Exact verified artifact being served.
    pub fn id(&self) -> &str {
        &self.candidate.id
    }
    /// Reviewer who authorized this deployed artifact; benchmark-only cores are private.
    pub fn reviewer(&self) -> Option<&str> {
        self.reviewer.as_deref()
    }
    /// Tenant bound into the checked specification.
    pub fn tenant(&self) -> &str {
        &self.candidate.spec.manifest.tenant
    }
    /// Component bound into the checked specification.
    pub fn component(&self) -> &str {
        &self.candidate.spec.manifest.component
    }
}

impl VerifiedCandidate {
    /// Measure the fixed benchmark against the actual native artifact. This is
    /// search execution, not deployment, so no deployment review is required.
    pub fn benchmark(self) -> Result<(Self, f64)> {
        let objective = self
            .spec
            .manifest
            .objective
            .as_ref()
            .context("optimization objective is required")?;
        ensure!(
            identity(&[&std::fs::read(&self.library)?]) == self.artifact_hash,
            "benchmark artifact mismatch"
        );
        let mut workload = Vec::new();
        for value in [
            objective.samples as u64,
            objective.iterations as u64,
            objective.inputs.len() as u64,
        ] {
            workload.extend_from_slice(&value.to_le_bytes());
        }
        for input in &objective.inputs {
            workload.extend_from_slice(&(input.len() as u64).to_le_bytes());
            workload.extend_from_slice(input.as_bytes());
        }
        let path = self._workspace.path();
        std::fs::write(path.join("workload.bin"), workload)?;
        let command = self.spec.benchmark_command(path, &self.benchmark)?;
        let output = crate::process::run(command, path, 60)?;
        let mut samples = output
            .lines()
            .map(str::parse::<f64>)
            .collect::<std::result::Result<Vec<_>, _>>()?;
        ensure!(
            samples.len() == objective.samples as usize
                && samples.iter().all(|s| s.is_finite() && *s > 0.0),
            "incomplete benchmark output"
        );
        samples.sort_by(f64::total_cmp);
        let score = match objective.metric {
            Metric::LatencyNs => samples[samples.len() / 2],
            Metric::ArtifactBytes => std::fs::metadata(&self.library)?.len() as f64,
            Metric::ThroughputPerSecond => {
                objective.inputs.len() as f64 * 1_000_000_000.0 / samples[samples.len() / 2]
            }
            Metric::Custom => {
                #[cfg(unix)]
                use std::os::unix::fs::PermissionsExt;
                let program = path.join("external-benchmark");
                std::fs::write(
                    &program,
                    self.spec
                        .external_benchmark
                        .as_ref()
                        .context("missing fixed benchmark executable")?,
                )?;
                #[cfg(unix)]
                std::fs::set_permissions(&program, std::fs::Permissions::from_mode(0o500))?;
                let mut command = self.spec.benchmark_command(path, &program)?;
                command.arg(&self.library);
                let metric = crate::process::run(command, path, 60)?
                    .trim()
                    .parse::<f64>()?;
                ensure!(
                    metric.is_finite() && metric > 0.0,
                    "invalid custom benchmark measurement"
                );
                metric
            }
        };
        ensure!(
            identity(&[&std::fs::read(&self.library)?]) == self.artifact_hash,
            "benchmark changed the checked artifact"
        );
        Ok((self, score))
    }
}
